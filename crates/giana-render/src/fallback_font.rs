const fn parse(art: &str) -> [u8; 8] {
    let b = art.as_bytes();
    let mut out = [0u8; 8];
    let mut row = 0;
    while row < 8 {
        let mut col = 0;
        while col < 8 {
            if b[row * 9 + col] == b'#' {
                out[row] |= 0x80 >> col;
            }
            col += 1;
        }
        row += 1;
    }
    out
}

const GLYPHS: [[u8; 8]; 36] = {
    let mut g = [[0u8; 8]; 36];
    let mut i = 0;
    while i < 36 {
        g[i] = parse(ART[i]);
        i += 1;
    }
    g
};

/// The glyph of an uppercase letter or a digit.
pub fn glyph(c: char) -> Option<[u8; 8]> {
    match c {
        'A'..='Z' => Some(GLYPHS[c as usize - 'A' as usize]),
        '0'..='9' => Some(GLYPHS[26 + c as usize - '0' as usize]),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn art_is_well_formed() {
        for (i, a) in ART.iter().enumerate() {
            assert_eq!(a.len(), 8 * 9 - 1, "glyph {i}");
            assert!(a.split(' ').all(|r| r.len() == 8 && r.chars().all(|c| c == '#' || c == '.')), "glyph {i}");
        }
        assert_eq!(glyph('A').unwrap()[3], 0b0111_1110);
        assert_eq!(glyph('9').unwrap()[7], 0);
        assert_eq!(glyph('a'), None);
    }
}
